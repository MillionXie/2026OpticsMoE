    if os.environ.get('CUDA_VISIBLE_DEVICES')!='' or len(os.environ.get('T12_SOURCE_COMMIT',''))!=40 or a.output.exists():raise ValueError('CPU-only new published TRAIN analysis required')
    import torch
    from .scene_tail_distill import load_cache
    from .white_reference_scene_probe import digest,write
    torch.set_num_threads(2);ready=json.loads((a.source/'report.json').read_text());path=a.source/'TRAIN_full_teacher_paths.pt'
    assert ready['complete']and ready['teacher_is_full_electronic_Qwen']and not ready['DEV_or_TEST_targets_created']
    assert digest(path)==ready['full_TRAIN_teacher_paths_sha256']
    saved=torch.load(path,map_location='cpu',weights_only=False,mmap=True);cache,cr=load_cache(a.student_cache)
    train={r['input_key']for r in cache['records']if r['split']=='train'};dev={r['input_key']for r in cache['records']if r['split']=='dev'}
    assert saved['all_TRAIN']and set(saved['paths'])<=train and not set(saved['paths'])&dev
    assert saved['teacher_sha256']=='662ff90f9a46670b28bf86d61629c59e4fb619ed69a62e4ae52ed8527ea76f76'and len(saved['paths'])==192
