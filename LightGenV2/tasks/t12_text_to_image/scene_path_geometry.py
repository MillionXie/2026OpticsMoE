"""TRAIN-only geometry diagnosis for a saved full electronic diffusion path.

The suggested grid minimizes teacher-path linear interpolation error. It has
not been trained or generated by this analysis, and establishes no quality gain.
"""
import argparse
import json
import math
import os
from pathlib import Path


def optimize_edges(costs,steps,max_interval=8):
    count=len(costs)-1
    if steps not in (6,8) or count!=30 or not 1<=max_interval<=30:raise ValueError('Explicit original thirty-step TRAIN grid required')
    best={(0,0):(0.,[0])}
    for used in range(1,steps+1):
        for end in range(1,count+1):
            options=[]
            for start in range(max(0,end-max_interval),end):
                previous=best.get((used-1,start))
                if previous is None:continue
                value=float(costs[start][end])
                if not math.isfinite(value) or value<0:raise ValueError('Finite nonnegative costs required')
                options.append((previous[0]+value,previous[1]+[end]))
            if options:best[used,end]=min(options,key=lambda q:(q[0],q[1]))
    if(steps,count)not in best:raise ValueError('Insufficient interval budget')
    score,edges=best[steps,count]
    return dict(edges=edges,TRAIN_geometry_cost=score,max_interval=max_interval)


def path_costs(paths,sigmas):
    import torch
    if len(sigmas)!=31 or sigmas[-1]!=0 or not all(a>b for a,b in zip(sigmas,sigmas[1:])):raise ValueError('Complete descending sigma grid required')
    normalized=torch.zeros((31,31,31),dtype=torch.float64);n=0
    for trajectory in paths:
        if trajectory.shape!=(31,4,64,64) or not torch.isfinite(trajectory).all():raise ValueError('Finite full teacher paths required')
        x=trajectory.double().flatten(1);gram=x@x.T/x.shape[1]
        # Average the normalized Gram terms before enumerating intervals: this
        # preserves each path's own normalization, without millions of scalar ops.
        normalized+=gram[None,:,:]/gram.diag().clamp_min(1.)[:,None,None];n+=1
    if n==0:raise ValueError('No TRAIN paths')
    normalized/=n;total=torch.zeros((31,31),dtype=torch.float64)
    for start in range(30):
        for stop in range(start+2,31):
            value=0.
            for middle in range(start+1,stop):
                lam=(sigmas[middle]-sigmas[start])/(sigmas[stop]-sigmas[start]);a=1-lam;g=normalized[middle]
                error=g[middle,middle]+a*a*g[start,start]+lam*lam*g[stop,stop]-2*a*g[middle,start]-2*lam*g[middle,stop]+2*a*lam*g[start,stop]
                value+=float(error.clamp_min(0))
            total[start,stop]=value
    return total.tolist()


